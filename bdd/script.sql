BEGIN;

DROP SCHEMA IF EXISTS shopwise CASCADE;
CREATE SCHEMA shopwise;
SET search_path TO shopwise, public;

-- 1. Un commerce possede ses propres clients et services.
CREATE TABLE commerces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL CHECK (length(trim(nom)) > 0),
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Un client est rattache a un commerce.
CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commerce_id BIGINT NOT NULL,
    nom VARCHAR(120) NOT NULL CHECK (length(trim(nom)) > 0),
    email VARCHAR(255) NOT NULL CHECK (length(trim(email)) > 0),
    telephone VARCHAR(30) NOT NULL CHECK (length(trim(telephone)) > 0),
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_clients_commerce FOREIGN KEY (commerce_id)
        REFERENCES commerces(id) ON DELETE RESTRICT,
    CONSTRAINT uq_clients_commerce_id UNIQUE (commerce_id, id)
);

-- Un meme email ne peut etre enregistre qu'une fois PAR commerce,
-- quelle que soit sa casse (ex. Alice@... == alice@...).
CREATE UNIQUE INDEX uq_clients_email_par_commerce
    ON clients (commerce_id, lower(email));

-- 3. Le service est choisi au moment du rendez-vous.
-- Le nombre de points par service est un CHOIX DE CONCEPTION :
-- il n'est pas fixe dans l'enonce, et peut etre ajuste par le commerçant.
CREATE TABLE services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commerce_id BIGINT NOT NULL,
    libelle VARCHAR(150) NOT NULL CHECK (length(trim(libelle)) > 0),
    duree_minutes INTEGER NOT NULL CHECK (duree_minutes > 0),
    points_attribues INTEGER NOT NULL DEFAULT 10 CHECK (points_attribues >= 0),
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_services_commerce FOREIGN KEY (commerce_id)
        REFERENCES commerces(id) ON DELETE RESTRICT,
    CONSTRAINT uq_services_commerce_id UNIQUE (commerce_id, id),
    CONSTRAINT uq_services_libelle_par_commerce UNIQUE (commerce_id, libelle)
);

-- 4. Rendez-vous : les deux cles etrangeres composites empechent
-- d'associer un client et un service de deux commerces differents.
CREATE TABLE rendez_vous (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commerce_id BIGINT NOT NULL,
    client_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    debut TIMESTAMPTZ NOT NULL,
    statut VARCHAR(12) NOT NULL DEFAULT 'PLANIFIE'
        CHECK (statut IN ('PLANIFIE', 'HONORE', 'ANNULE')),
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rdv_commerce FOREIGN KEY (commerce_id)
        REFERENCES commerces(id) ON DELETE RESTRICT,
    CONSTRAINT fk_rdv_client_du_commerce FOREIGN KEY (commerce_id, client_id)
        REFERENCES clients(commerce_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_rdv_service_du_commerce FOREIGN KEY (commerce_id, service_id)
        REFERENCES services(commerce_id, id) ON DELETE RESTRICT,
    CONSTRAINT uq_rdv_id_client UNIQUE (id, client_id)
);

-- Index adaptes aux filtres demandes (date, statut, client).
CREATE INDEX idx_rdv_commerce_date
    ON rendez_vous (commerce_id, debut);
CREATE INDEX idx_rdv_commerce_statut_date
    ON rendez_vous (commerce_id, statut, debut);
CREATE INDEX idx_rdv_client_date
    ON rendez_vous (client_id, debut);

-- 5. Les points sont historises dans un journal de transactions.
-- Une transaction de gain par rendez-vous au maximum : anti-doublon.
-- Le FK composite garantit que le gain concerne le client du RDV.
CREATE TABLE transactions_fidelite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rendez_vous_id BIGINT NOT NULL UNIQUE,
    client_id BIGINT NOT NULL,
    points INTEGER NOT NULL CHECK (points > 0),
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_transactions_client FOREIGN KEY (client_id)
        REFERENCES clients(id) ON DELETE RESTRICT,
    CONSTRAINT fk_transactions_rdv_client FOREIGN KEY (rendez_vous_id, client_id)
        REFERENCES rendez_vous(id, client_id) ON DELETE RESTRICT
);

CREATE INDEX idx_transactions_client_date
    ON transactions_fidelite (client_id, cree_le DESC);

-- Le solde est CALCULE : aucun champ solde redondant dans clients.
CREATE VIEW v_soldes_fidelite AS
SELECT c.id AS client_id,
       c.commerce_id,
       c.nom,
       COALESCE(SUM(t.points), 0)::BIGINT AS solde_points
FROM clients c
LEFT JOIN transactions_fidelite t ON t.client_id = c.id
GROUP BY c.id, c.commerce_id, c.nom;

